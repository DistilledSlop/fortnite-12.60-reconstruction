from types import SimpleNamespace
HERE=Path(__file__).resolve().parent
CONTRACT=HERE/'contract.json'
def digest(path):
 h=hashlib.sha256()
 with open(path,'rb') as f:
  for b in iter(lambda:f.read(1<<20),b''):h.update(b)
 return h.hexdigest()
def need(value,msg):
 if not value:raise ValueError(msg)
def load(path):return json.loads(Path(path).read_text())
def pinned(item):
 need(Path(item['path']).is_file() and digest(item['path'])==item['sha256'],'artifact pin '+item['path']);return Path(item['path'])
def context():
 c=load(CONTRACT)
 for item in c['context_tools'].values():pinned(item)
 for item in c['frozen_receipts']:pinned(item)
 baseline=load(pinned(c['baseline_context_expectations']));expected=load(HERE/'source-expectations.json')
 need(expected==c['expected_source'] and len(expected)==len(baseline)==6,'exact future six source expectations')
 changed={k for k in baseline if expected[k]!=baseline[k]}
 need(changed=={'porting/gen_native_classes.py','porting/native/Source/FortniteGame/FortniteGame.cpp'},'only approved two future context pin changes')
 sys.path.insert(0,str(Path(c['context_tools']['provenance.py']['path']).parent))
 p=importlib.import_module('provenance');p.HERE=HERE;p.pin();return p,c

def normalized_native(data):
 # Only the reflection path in the first generated comment may differ.
 # CPP has a fixed second sentence on that line; header does not.
 lines=data.splitlines(keepends=True)
 if lines:
  match=re.fullmatch(rb'// Generated by porting/gen_native_classes\.py --promote from (?:[^\r\n]*/)?fortnite_game_reflection\.json(\.(?: Do not edit by hand\.)?)(\r?\n)?',lines[0])
  if match:
   return b'// Generated by porting/gen_native_classes.py --promote from <reflection>/fortnite_game_reflection.json'+match[1]+(match[2] or b'')+b''.join(lines[1:])
 return data

def source_check(p,c,root):
 for item in c['inputs']:pinned(item)
 for rel,item in c['approved_generator_inputs'].items():
  pinned(item);need((root/rel).is_file() and digest(root/rel)==item['sha256'],'installed generator policy/input '+rel)
 for rel,item in c['approved_native'].items():
  approved=pinned(item);actual=root/'porting/native/Source'/rel
  need(actual.is_file() and normalized_native(actual.read_bytes())==normalized_native(approved.read_bytes()),'approved native source '+rel)
 need(digest(root/'porting/gen_native_classes.py')==c['generator']['sha256'],'approved activation generator')
 for rel,sha in c['expected_source'].items():need(digest(root/rel)==sha,'future context source '+rel)

def snapshot_check(p,c,out):
 st=load(out/'start.json');root=Path(st['workspace']);source_check(p,c,root)
 need(p.tree(root/'porting/native/Source')==st['snapshot']['source_tree'] and p.engine_state(Path(st['snapshot']['engine']['root']))==st['snapshot']['engine'] and digest(root/'porting/gen_native_classes.py')==st['snapshot']['generator'],'immutable source/build closure')
 a=load(out/'activation.start.json');need(a['context_start_sha256']==digest(out/'start.json') and a['contract_sha256']==digest(CONTRACT) and a['binder_sha256']==digest(__file__) and a['metadata_tool_sha256']==digest(HERE/'activation_metadata.py') and a['implementation_tool_sha256']==digest(HERE/'implementation_link.py'),'activation start pins')
 return st,root

def artifact(p,path,since,fresh=True):
 need(path.is_file() and (not fresh or path.stat().st_mtime_ns>=since),'fresh artifact '+str(path));return {'path':str(path.resolve()),'sha256':digest(path),'mtime_ns':path.stat().st_mtime_ns}

def collect(p,out,st,root):
 targets={}
 for target in ('FortniteLinux','FortniteLinuxServer'):
  base=root/'porting/native/Intermediate/Build/Linux/B4D820EA'/target
  specs={'base_cpp':('CommonUI',root/'porting/native/Source/CommonUI/Generated/UCommonActivatableWidget.cpp',False),'base_glue':('CommonUI',base/'Inc/CommonUI/UCommonActivatableWidget.gen.cpp',True),'probe_cpp':('FortniteGame',root/'porting/native/Source/FortniteGame/ActivationBaseProbe.cpp',False),'probe_glue':('FortniteGame',base/'Inc/FortniteGame/ActivationBaseProbe.gen.cpp',True)}
  result={}
  for name,(module,cpp,fresh) in specs.items():
   unit=p.unity.resolve(base/'Development'/module,cpp,st['start_ns'])
   result[name]={'cpp':artifact(p,cpp,st['start_ns'],fresh),**{k:artifact(p,v,st['start_ns'],k=='object') for k,v in unit.items()}}
  # Header freshness belongs to this build's UHT output, not the old offline copy.
  result['headers']=[artifact(p,base/'Inc'/mod/name,st['start_ns']) for mod,name in [('CommonUI','UCommonActivatableWidget.generated.h'),('FortniteGame','ActivationBaseProbe.generated.h')]]
  import implementation_link
  result['link_recipe']=implementation_link.recipe(base/'Development'/('Link-'+target+'.link.sh'),base/'Development'/(target+'.response'),root/'porting/native/Binaries/Linux'/target,[Path(result[k]['object']['path']) for k in specs])
  targets[target]=result
 return targets

def start(a):
 p,c=context();source_check(p,c,a.workspace.resolve());p.start(a)
 p.write_new(a.out/'activation.start.json',{'schema':'activation-start-v1','context_start_sha256':digest(a.out/'start.json'),'contract_sha256':digest(CONTRACT),'binder_sha256':digest(__file__),'metadata_tool_sha256':digest(HERE/'activation_metadata.py'),'implementation_tool_sha256':digest(HERE/'implementation_link.py')})
def build(a):
 p,c=context();snapshot_check(p,c,a.out);p.build_target(a)
def finish(a):
 p,c=context();st,root=snapshot_check(p,c,a.out);p.finish(a)
 p.write_new(a.out/'activation.build.json',{'schema':'activation-build-v1','context_build_sha256':digest(a.out/'build.json'),'activation_start_sha256':digest(a.out/'activation.start.json'),'targets':collect(p,a.out,st,root),'finished_ns':time.time_ns()})

def activation_command(binary,case,travel,args):
 need(case=='activation','activation case');extra=list(args);extra=extra[1:] if extra and extra[0]=='--' else extra
 # No caller-controlled startup/phase/driver flags: keep this driver isolated.
 need(not extra,'activation runner accepts no extra arguments')
 return [str(binary),'-ActivationBaseProbe','-stdout','-NOCONSOLE']
def run(a):
 p,c=context();snapshot_check(p,c,a.out);b=load(a.out/'activation.build.json');need(b['context_build_sha256']==digest(a.out/'build.json'),'activation/context build chain')
 a.case='activation';a.travel_map='/Engine/Maps/Entry';a.args=[]
 # Reuse executable inode, before/after binary hash, timeout, cwd and log recorder.
 # This changes command construction only; the context implementation stays pinned.
 old=p.build_live_command;p.build_live_command=activation_command
 try:p.run(a)
 finally:p.build_live_command=old

