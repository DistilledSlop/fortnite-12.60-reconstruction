#!/usr/bin/env python3
"""Derive the ordered tag->EDeathCause priority table of 0x141a5f1c0 (AFortPlayerStateAthena::ToDeathCause).

Reads (read-only): porting/generated/native96-impl/0x141a5f1c0.c and native/.../EDeathCause.h.
Writes ToDeathCause_TagRows.inc. Row order IS the first-match priority of the native if-ladder.
Every block is matched against a strict shape; anything unexpected aborts (no guessing).
Usage: python3 -I gen_death_cause_rows.py <repo-porting-dir> <out.inc>
"""
import re, sys
root, out = sys.argv[1], sys.argv[2]
src = open(f'{root}/generated/native96-impl/0x141a5f1c0.c').read().split('\n')
enum = {}
for l in open(f'{root}/native/Source/FortniteGame/Generated/EDeathCause.h'):
    m = re.match(r'\s*(\w+) = (\d+),', l)
    if m: enum[int(m.group(2))] = m.group(1)
starts = [i for i, l in enumerate(src) if 'lVar6 = FUN_141ed1800' in l]
assert len(starts) == 46
ends = starts[1:] + [len(src)]
def code(s): return int(s, 16) if s.startswith('0x') else int(s)
stage1, gate, stage2 = [], None, []
for a, b in zip(starts, ends):
    blk = '\n'.join(src[a:b])
    off = int(re.search(r'FName_EqualsEName\(\*\(int \*\)\(lVar6 \+ (0x[0-9a-f]+)\)', blk).group(1), 16)
    rets = re.findall(r'return ([0-9a-fx\']+);', blk)
    if 'return param_2 * ' in blk:
        stage1.append((off, 'DBNO_SELECT', 'bWasDBNO ? 0x11 : 0x01', 'inline'))
    elif 'return -(param_2' in blk:
        stage1.append((off, 'DBNO_SELECT', 'bWasDBNO ? 0x11 : 0x00', 'inline'))
    elif off == 0xa80:
        stage1.append((off, 'NESTED', '0x638:6:7', 'inline'))
    elif off == 0x638:
        continue  # consumed by the nested 0xa80 row; verified below
    elif off == 0xab8:
        gate = off
    elif off == 0x448:
        stage2.append((off, 'LAST', '0x2e:0x32', 'helper'))
    elif gate is None:
        assert len(set(rets)) == 1, (hex(off), rets)
        stage1.append((off, 'FIXED', str(code(rets[0])), 'inline'))
    else:
        assert len(rets) == 1, (hex(off), rets)
        stage2.append((off, 'FIXED', str(code(rets[0])), 'helper'))
# nested 0xa80 sanity: 0x638 -> 6, fallthrough 7
t = '\n'.join(src)
assert 'lVar6 + 0x638' in t and 'return 6;' in t and 'return 7;' in t
def cname(v):
    return 'EDeathCause::' + enum[v]
def row(off, kind, val, mode):
    if kind == 'FIXED': return f'\t{{ 0x{off:x}, EFortToDeathCauseRow::Fixed, {cname(int(val))}, {cname(int(val))} }},'
    if kind == 'DBNO_SELECT':
        a, b = (1, 0x11) if val.endswith('0x01') else (0, 0x11)
        return f'\t{{ 0x{off:x}, EFortToDeathCauseRow::SelectByDBNO, {cname(a)}, {cname(b)} }}, // !DBNO / DBNO'
    if kind == 'NESTED':
        return f'\t{{ 0x{off:x}, EFortToDeathCauseRow::NestedSniper, {cname(7)}, {cname(6)} }}, // else-result / result-when-tag-0x638'
    if kind == 'LAST':
        return f'\t{{ 0x{off:x}, EFortToDeathCauseRow::LastRow, {cname(0x32)}, {cname(0x2e)} }}, // no-match / match'
with open(out, 'w') as f:
    f.write('// GENERATED by gen_death_cause_rows.py from native96-impl/0x141a5f1c0.c. Row order = native first-match priority.\n')
    f.write('// Columns: FFortGameplayTags singleton byte offset of the FGameplayTag slot, row kind, result A, result B.\n')
    f.write('// Stage 1 rows use the inlined exact-match scan (GameplayTags then ParentTags). Stage 2 rows run only when the 0xab8 gate tag is absent.\n')
    f.write('static const FFortToDeathCauseRow GToDeathCauseStage1[] = {\n')
    f.write('\n'.join(row(*r) for r in stage1) + '\n};\n')
    f.write(f'static constexpr uint32 GToDeathCauseGateSlot = 0x{gate:x}; // present => EDeathCause::{enum[0xe]} (0xe)\n')
    f.write('static const FFortToDeathCauseRow GToDeathCauseStage2[] = {\n')
    f.write('\n'.join(row(*r) for r in stage2) + '\n};\n')
print(len(stage1), 'stage1 rows,', len(stage2), 'stage2 rows, gate', hex(gate))
