#!/usr/bin/env python3
"""Generate the native lookup table from the captured first-stage evidence."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = Path(__file__).with_name('first-stage.json')
OUTPUT = ROOT / 'porting/native/Source/FortniteGame/Private/LegacyMcpDeploymentTable.inl'
rows = json.loads(SOURCE.read_text(encoding='utf-8'))['names']
assert len(rows) == 62
assert len({row['name'].lower() for row in rows}) == 62
assert len({row['third_output'] for row in rows}) == 61
for row in rows:
    assert row['result'] is True
    for field in ('name', 'second_output', 'third_output'):
        assert re.fullmatch(r'[A-Za-z0-9]+', row[field]), (field, row[field])
lines = ['// Generated by porting/behavior/mcp_deployment_mapping_runtime/generate_native_table.py.',
         '// Source: first-stage.json. Do not edit by hand.']
lines.extend('    { TEXT("%s"), TEXT("%s"), TEXT("%s") },' %
             (row['name'], row['second_output'], row['third_output']) for row in rows)
OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
