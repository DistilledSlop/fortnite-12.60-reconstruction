"""Generate server/cosmetic_variant_data.py from Cue4Inspect --property-report output.

usage: gen_cosmetic_variants.py OUT_DIR_WITH_REPORTS OUTPUT.py
Each report is JSON (first '{' onward). Channel = VariantChannelTag last segment, option
value = CustomizationVariantTag last segment. active = bIsDefault option, owned = options
with bStartUnlocked and no UnlockingItemDef.
"""
import glob, json, os, sys

PREFIX = {
    "AthenaCharacterItemDefinition": "AthenaCharacter", "AthenaBackpackItemDefinition": "AthenaBackpack",
    "AthenaPickaxeItemDefinition": "AthenaPickaxe", "AthenaGliderItemDefinition": "AthenaGlider",
    "AthenaSkyDiveContrailItemDefinition": "AthenaSkyDiveContrail", "AthenaDanceItemDefinition": "AthenaDance",
    "AthenaItemWrapDefinition": "AthenaItemWrap", "AthenaLoadingScreenItemDefinition": "AthenaLoadingScreen",
    "AthenaMusicPackItemDefinition": "AthenaMusicPack", "AthenaToyItemDefinition": "AthenaDance",
    "AthenaSprayItemDefinition": "AthenaDance", "AthenaEmojiItemDefinition": "AthenaDance",
}
OPTS = ("MaterialOptions", "ParticleOptions", "PartOptions", "MeshOptions")


def val(props, name):
    for p in props:
        if p["name"] == name:
            return p.get("value")


def tag(props, name):
    v = val(props, name)
    if isinstance(v, list):
        for q in v:
            if q.get("name") == "TagName":
                return q["value"]
    return None


def main(src, out):
    table = {}
    for path in sorted(glob.glob(os.path.join(src, "*.txt"))):
        raw = open(path, encoding="utf-8", errors="replace").read()
        try:
            d = json.loads(raw[raw.index("{"):])
        except Exception:
            continue
        exports = d.get("exports", [])
        prefix = next((PREFIX[e["exportType"]] for e in exports if e.get("exportType") in PREFIX), None)
        if not prefix:
            continue
        asset = os.path.basename(path)[:-4]
        channels = []
        for e in exports:
            if not e.get("exportType", "").startswith("FortCosmetic"):
                continue
            ctag = tag(e.get("properties", []), "VariantChannelTag")
            if not ctag:
                continue
            for p in e.get("properties", []):
                if p["name"] not in OPTS:
                    continue
                opts = []
                for o in p["value"]:
                    otag = tag(o, "CustomizationVariantTag")
                    if not otag:
                        continue
                    unlocking = val(o, "UnlockingItemDef")
                    locked = bool(unlocking and unlocking.get("path"))
                    opts.append((otag.rsplit(".", 1)[-1], val(o, "bIsDefault") is True,
                                 val(o, "bStartUnlocked") is not False and not locked))
                if not opts:
                    continue
                default = next((t for t, dflt, _ in opts if dflt), opts[0][0])
                owned = [t for t, _, unlocked in opts if unlocked]
                if default not in owned:
                    owned.append(default)
                channels.append({"channel": ctag.rsplit(".", 1)[-1], "active": default, "owned": owned})
        if channels:
            table[f"{prefix}:{asset}".casefold()] = channels
    with open(out, "w") as f:
        f.write('"""Default/owned cosmetic style variants, generated by tools/gen_cosmetic_variants.py\n'
                'from the 12.60 cooked assets (Cue4Inspect property report). Keys are casefolded template ids."""\n\n')
        f.write("VARIANTS = {\n")
        for k in sorted(table):
            f.write(f"    {k!r}: {json.dumps(table[k], separators=(',', ':'))},\n")
        f.write("}\n")
    print(len(table), "cosmetics with variants")


main(*sys.argv[1:3])
